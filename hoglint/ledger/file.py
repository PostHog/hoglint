"""The generated ledger: one sorted file, one line per (rule, identity) with a count, no prose.

Format: two header lines, then tab-separated lines `rule<TAB>column...<TAB>count`.
The header carries the fact schema version and the policy hash the lines were written under.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

HEADER = "# hoglint ledger, generated by `hoglint check --write-ledger`. Do not edit by hand."
ESCAPES = (("\\", "\\\\"), ("\t", "\\t"), ("\n", "\\n"))

LineKey = tuple[str, tuple[str, ...]]
LEVEL_PREFIX = "level:"  # the rule column of a level line: `level:<name><TAB><group>`


def level_line(name: str, group: str) -> LineKey:
    return LEVEL_PREFIX + name, (group,)


def is_level_line(key: LineKey) -> bool:
    return key[0].startswith(LEVEL_PREFIX)


def escape(value: str) -> str:
    for raw, escaped in ESCAPES:
        value = value.replace(raw, escaped)
    return value


def unescape(value: str) -> str:
    out: list[str] = []
    index = 0
    while index < len(value):
        if value[index] == "\\" and index + 1 < len(value):
            out.append({"\\": "\\", "t": "\t", "n": "\n"}.get(value[index + 1], value[index + 1]))
            index += 2
            continue
        out.append(value[index])
        index += 1
    return "".join(out)


def render_key(key: LineKey) -> str:
    return "\t".join(escape(part) for part in (key[0], *key[1]))


def parse_key(text: str) -> LineKey:
    parts = [unescape(part) for part in text.split("\t")]
    return parts[0], tuple(parts[1:])


@dataclass(frozen=False, slots=True)
class LedgerFile:
    schema: int | None = None
    policy: str = ""
    lines: dict[LineKey, int] = field(default_factory=dict)
    problems: list[str] = field(default_factory=list)
    exists: bool = False

    @staticmethod
    def parse(text: str) -> LedgerFile:
        ledger = LedgerFile(exists=True)
        for number, raw in enumerate(text.splitlines(), start=1):
            if not raw.strip():
                continue
            if raw.startswith("#"):
                ledger.read_header(raw)
                continue
            parts = [unescape(part) for part in raw.split("\t")]
            if len(parts) < 2 or not parts[-1].isdigit():
                ledger.problems.append(f"line {number}: expected `rule<TAB>columns...<TAB>count`")
                continue
            key = (parts[0], tuple(parts[1:-1]))
            if key in ledger.lines:
                ledger.problems.append(f"line {number}: duplicate line {render_key(key)}")
            ledger.lines[key] = int(parts[-1])
        return ledger

    @staticmethod
    def read(path: Path) -> LedgerFile:
        if not path.is_file():
            return LedgerFile()
        return LedgerFile.parse(path.read_text())

    def read_header(self, raw: str) -> None:
        for token in raw.lstrip("#").split():
            name, _, value = token.partition("=")
            if name == "schema" and value.isdigit():
                self.schema = int(value)
            elif name == "policy":
                self.policy = value

    def render(self) -> str:
        out = [HEADER, f"# schema={self.schema} policy={self.policy}"]
        for key in sorted(self.lines):
            out.append(f"{render_key(key)}\t{self.lines[key]}")
        return "\n".join(out) + "\n"

    def write(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.render())
